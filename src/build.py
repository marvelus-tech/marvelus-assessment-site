#!/usr/bin/env python3
"""Build the static site into the repo root. Usage: python3 src/build.py"""
import json, re, sys, pathlib, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from content_core import *
import engine
from engine import PAGES, render_page, SITE
import pages_a, pages_b, pages_c

OUT = ROOT

def envelope(tool, data, delight=None, ok=True, meta_extra=None):
    meta = {"tool": tool, "version": "1.0", "site": SITE + "/", "generated_at": CFG["buildDate"],
            "draft_notice": "Draft site: placeholders remain and pages are marked noindex." if CFG["noindex"] else None}
    if meta_extra:
        meta.update(meta_extra)
    env = {"ok": ok, "data": data, "meta": meta}
    if delight and ok:
        env["delight"] = delight
    return env

TOOLS = [
    ("get_offers", "List MarvelUs's three equal offers: digital support, SEO and the Business Assessment.", {}),
    ("get_assessment_details", "Price, duration, scoring dimensions, process and method for the Business Assessment (AI Readiness).", {}),
    ("get_pricing", "What is priced and what is not. The assessment is $1,000 AUD plus GST. Other offers are scoped to the business.", {}),
    ("get_sample_report", "The example report, with invented data clearly labelled as an example.", {}),
    ("start_quiz_preview", "Open the free 9 step quiz preview on this page when it is available, and describe its steps. Nothing is stored or sent.", {"open": {"type": "boolean", "description": "Open the quiz panel if this page has one."}}),
    ("get_contact", "Contact state. Email and phone are placeholders until MarvelUs publishes them. Booking lives at the booking page.", {}),
    ("get_site_map", "Every page on the site with a one line note.", {}),
]
DELIGHT = {
    "get_offers": {"line": "Three offers, equal weight. Pick the one that fits today.", "tone": "plain", "emoji": "🧭", "media_url": None},
    "get_assessment_details": {"line": "One call, one report, the lowest dimension first.", "tone": "plain", "emoji": "📋", "media_url": None},
    "get_pricing": {"line": "One fixed price, the rest scoped to the business.", "tone": "plain", "emoji": "💬", "media_url": None},
    "get_sample_report": {"line": "Invented numbers, real maths.", "tone": "dry", "emoji": "🧮", "media_url": None},
    "start_quiz_preview": {"line": "About a minute, and nothing leaves the browser.", "tone": "plain", "emoji": "⏱️", "media_url": None},
    "get_contact": {"line": "No public email or phone yet. The booking page is open.", "tone": "plain", "emoji": "📮", "media_url": None},
    "get_site_map": {"line": "Every page, one line each.", "tone": "plain", "emoji": "🗺️", "media_url": None},
}

def write(path, text):
    p = OUT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")

def main():
    ad = agent_data()
    # pages
    ph_counts = collections.Counter()
    per_page = {}
    for meta in PAGES:
        doc, phs = render_page(meta)
        rel = meta["path"].lstrip("/")
        out = rel if rel.endswith(".html") else (rel + "index.html")
        write(out, doc)
        per_page[meta["path"]] = len(phs)
        ph_counts.update(phs)
    # data assets
    tools = [{"name": n, "description": d, "inputSchema": {"type": "object", "properties": props, "additionalProperties": False}} for n, d, props in TOOLS]
    site = {"config": {"siteUrl": SITE, "purchaseUrl": CFG["purchaseUrl"], "bookingPath": CFG["bookingPath"],
                       "contactEmail": CFG["contactEmail"] or None, "contactPhone": CFG["contactPhone"] or None,
                       "noindex": CFG["noindex"], "buildDate": CFG["buildDate"]},
            "data": ad, "tools": tools, "delight": DELIGHT}
    write("assets/js/site-data.js", "/* Generated by src/build.py from site.config.json. Do not edit. */\nwindow.MARVELUS_SITE = " + json.dumps(site, indent=1, ensure_ascii=False) + ";\n")
    quiz = {"industries": INDUSTRIES, "packs": PACKS, "hours": HOUR_BANDS, "revenue": REVENUE_BANDS,
            "toolsDefault": TOOLS_DEFAULT, "costDefault": COST_DEFAULT, "roles": ROLES, "heard": HEARD,
            "rate": RATE, "weeks": WEEKS, "generatingMs": 6000, "purchaseUrl": CFG["purchaseUrl"], "priceLabel": PRICE,
            "priceLong": PRICE_LONG, "call": CALL, "bookPath": CFG["bookingPath"]}
    write("assets/js/quiz-data.js", "/* Generated by src/build.py. Do not edit. */\nwindow.MARVELUS_QUIZ = " + json.dumps(quiz, indent=1, ensure_ascii=False) + ";\n")
    manifest = {
        "schema_version": "1.0",
        "name": "MarvelUs",
        "description": "Agent manifest for the MarvelUs site. The same tools are registered through WebMCP (navigator.modelContext) on every page.",
        "site": SITE + "/",
        "status": "draft: placeholders remain, pages are noindex" if CFG["noindex"] else "live",
        "envelope": {"ok": "boolean", "data": "object, facts only", "meta": "object", "delight": "optional object {line, tone, emoji, media_url}, skipped on errors"},
        "tools": [dict(t, response=envelope(t["name"], tool_data(t["name"], ad), DELIGHT[t["name"]])) for t in tools],
    }
    write("agents.json", json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    write(".well-known/agent.json", json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    # sitemap, robots, favicon
    urls = [m["path"] for m in PAGES if m["kind"] != "404"]
    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u in urls:
        sm.append(f"  <url><loc>{SITE}{u}</loc><lastmod>{CFG['buildDate']}</lastmod></url>")
    sm.append("</urlset>")
    write("sitemap.xml", "\n".join(sm) + "\n")
    write("robots.txt", f"# Draft build: pages carry noindex while placeholders remain.\nUser-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n")
    write("assets/favicon.svg", '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" fill="#0b5d57"/><path d="M8 24V9h3.2l4.8 7.6L20.8 9H24v15h-3V14.2l-3.9 6.1h-2.2L11 14.2V24z" fill="#fbfaf7"/></svg>\n')
    uniq = collections.Counter(k for k, _ in engine.ALL_PH)
    (OUT / "placeholders.json").write_text(json.dumps({"unique_by_type": dict(uniq), "unique_total": sum(uniq.values()),
        "occurrences_by_type": dict(ph_counts), "occurrences_total": sum(ph_counts.values()), "by_page": per_page,
        "note": "Unique counts de-duplicate repeated footer and header placeholders. Remove this file when launching."}, indent=1) + "\n")
    print(f"built {len(PAGES)} pages; unique placeholders: {dict(uniq)} total {sum(uniq.values())}; occurrences {sum(ph_counts.values())}")

def tool_data(name, ad):
    return {
        "get_offers": {"offers": ad["offers"], "note": "The three offers have equal weight."},
        "get_assessment_details": ad["assessment"],
        "get_pricing": ad["pricing"],
        "get_sample_report": ad["sample_report"],
        "start_quiz_preview": ad["quiz"],
        "get_contact": ad["contact"],
        "get_site_map": {"pages": ad["site_map"], "manifest": SITE + "/agents.json"},
    }[name]

if __name__ == "__main__":
    main()
